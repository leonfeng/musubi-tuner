#!/usr/bin/env python3
"""Sort Krea 2 dataset images into resolution-tier subdirectories.

Walks a flat source image directory, assigns each image-caption pair to the
resolution tier whose musubi-tuner bucket minimizes resize, moves the pair into
``{source_dir}/{tier}/``, then rewrites ``configs/krea2.toml`` so each active
tier has its own dataset entry and cache subdirectory.
"""

from __future__ import annotations

import argparse
import logging
import math
import shutil
from collections import Counter
from pathlib import Path

import toml
from PIL import Image

from musubi_tuner.dataset.architectures import ARCHITECTURE_KREA2
from musubi_tuner.dataset.bucket import BucketSelector
from musubi_tuner.dataset.media_utils import IMAGE_EXTENSIONS

logger = logging.getLogger(__name__)

DEFAULT_SOURCE_DIR = "dataset"
DEFAULT_CONFIG_PATH = "configs/krea2.toml"
DEFAULT_TIERS = (896, 1024, 1280, 1536)

CONFIG_PREAMBLE = """\
# Krea 2 LoRA dataset config for musubi-tuner
# Use with: --dataset_config configs/krea2.toml
#
# Generated by sort_krea2_dataset.py: one subdirectory per resolution tier.
# musubi-tuner has no target_res setting; each tier is a separate dataset entry
# with its own cache subdirectory (required by musubi-tuner).
"""


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Sort Krea 2 images into resolution-tier subdirectories and update configs/krea2.toml."
    )
    parser.add_argument(
        "--source-dir",
        type=Path,
        default=Path(DEFAULT_SOURCE_DIR),
        help=f"Flat source image directory (default: {DEFAULT_SOURCE_DIR})",
    )
    parser.add_argument(
        "--config",
        type=Path,
        default=Path(DEFAULT_CONFIG_PATH),
        help=f"Dataset config to rewrite (default: {DEFAULT_CONFIG_PATH})",
    )
    parser.add_argument(
        "--tiers",
        type=str,
        default=None,
        help="Comma-separated resolution tiers to consider (default: read from config or 896,1024,1280,1536)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print planned moves and config changes without writing files",
    )
    return parser.parse_args()


def read_image_size(path: Path) -> tuple[int, int] | None:
    try:
        with Image.open(path) as image:
            width, height = image.size
        if width <= 0 or height <= 0:
            return None
        return int(width), int(height)
    except Exception:
        logger.warning("Skipping unreadable image: %s", path)
        return None


def iter_top_level_images(source_dir: Path, caption_extension: str) -> list[Path]:
    """Return image paths directly under source_dir that have a caption file."""
    if not source_dir.is_dir():
        raise FileNotFoundError(f"Source directory not found: {source_dir}")

    caption_suffix = caption_extension if caption_extension.startswith(".") else f".{caption_extension}"
    images: list[Path] = []
    for entry in sorted(source_dir.iterdir()):
        if not entry.is_file():
            continue
        if entry.suffix not in IMAGE_EXTENSIONS:
            continue
        caption_path = entry.with_suffix(caption_suffix)
        if not caption_path.is_file():
            logger.warning("Skipping image without caption: %s", entry)
            continue
        images.append(entry)
    return images


def load_config(config_path: Path) -> tuple[str, dict]:
    if config_path.is_file():
        text = config_path.read_text(encoding="utf-8")
        marker = "[general]"
        preamble = text.split(marker, 1)[0] if marker in text else CONFIG_PREAMBLE
        config = toml.loads(text)
        return preamble, config

    return CONFIG_PREAMBLE, {
        "general": {
            "caption_extension": ".txt",
            "batch_size": 1,
            "enable_bucket": True,
            "bucket_no_upscale": False,
        }
    }


def tiers_from_config(config: dict) -> list[int]:
    tiers: list[int] = []
    for dataset in config.get("datasets", []):
        resolution = dataset.get("resolution")
        if resolution is None:
            continue
        if isinstance(resolution, int):
            tiers.append(resolution)
        else:
            tiers.append(int(resolution[0]))
    return sorted(set(tiers))


def parse_tiers_arg(value: str | None, config: dict) -> list[int]:
    if value:
        tiers = [int(part.strip()) for part in value.split(",") if part.strip()]
    else:
        tiers = tiers_from_config(config)
    if not tiers:
        tiers = list(DEFAULT_TIERS)
    return sorted(set(tiers))


def choose_resolution_tier(
    width: int,
    height: int,
    tiers: list[int],
    *,
    bucket_no_upscale: bool,
) -> int:
    """Pick the tier whose Krea 2 bucket area is closest to the native image area."""
    image_size = (width, height)
    image_area = width * height
    best_tier = tiers[0]
    best_score = float("inf")

    for tier in tiers:
        selector = BucketSelector(
            (tier, tier),
            enable_bucket=True,
            no_upscale=bucket_no_upscale,
            architecture=ARCHITECTURE_KREA2,
        )
        bucket_width, bucket_height = selector.get_bucket_resolution(image_size)
        scale = (bucket_width * bucket_height) / image_area
        score = abs(math.log(scale))
        if score < best_score:
            best_score = score
            best_tier = tier

    return best_tier


def move_image_caption_pair(
    image_path: Path,
    caption_path: Path,
    destination_dir: Path,
    *,
    dry_run: bool,
) -> None:
    destination_dir.mkdir(parents=True, exist_ok=True)
    destination_image = destination_dir / image_path.name
    destination_caption = destination_dir / caption_path.name

    if destination_image.exists() or destination_caption.exists():
        raise FileExistsError(
            f"Refusing to overwrite existing file in {destination_dir}: {image_path.name}"
        )

    logger.info("Move %s -> %s", image_path, destination_image)
    if dry_run:
        return

    shutil.move(image_path, destination_image)
    shutil.move(caption_path, destination_caption)


def render_config(
    *,
    preamble: str,
    general: dict,
    tiers: list[int],
    source_dir: Path,
) -> str:
    lines = [preamble.rstrip(), "", "[general]"]
    for key in ("caption_extension", "batch_size", "enable_bucket", "bucket_no_upscale"):
        if key in general:
            value = general[key]
            if isinstance(value, bool):
                rendered = "true" if value else "false"
            elif isinstance(value, str):
                rendered = f'"{value}"'
            else:
                rendered = str(value)
            lines.append(f"{key} = {rendered}")

    source_name = source_dir.as_posix().rstrip("/")
    for tier in tiers:
        lines.extend(
            [
                "",
                "[[datasets]]",
                f'image_directory = "{source_name}/{tier}"',
                f'cache_directory = "cache/{tier}"',
                f"resolution = {tier}",
                "num_repeats = 1",
            ]
        )
    lines.append("")
    return "\n".join(lines)


def tier_dir_has_images(tier_dir: Path, caption_extension: str) -> bool:
    if not tier_dir.is_dir():
        return False
    caption_suffix = caption_extension if caption_extension.startswith(".") else f".{caption_extension}"
    for entry in tier_dir.iterdir():
        if entry.is_file() and entry.suffix in IMAGE_EXTENSIONS:
            if entry.with_suffix(caption_suffix).is_file():
                return True
    return False


def sort_dataset(
    *,
    source_dir: Path,
    config_path: Path,
    tiers: list[int],
    dry_run: bool,
) -> Counter[int]:
    preamble, config = load_config(config_path)
    general = config.get("general", {})
    caption_extension = general.get("caption_extension", ".txt")
    bucket_no_upscale = bool(general.get("bucket_no_upscale", False))

    tier_counts: Counter[int] = Counter()
    image_paths = iter_top_level_images(source_dir, caption_extension)
    if not image_paths:
        logger.warning("No image-caption pairs found in %s", source_dir)
    else:
        for image_path in image_paths:
            size = read_image_size(image_path)
            if size is None:
                continue

            tier = choose_resolution_tier(*size, tiers, bucket_no_upscale=bucket_no_upscale)
            tier_counts[tier] += 1
            caption_path = image_path.with_suffix(caption_extension)
            destination_dir = source_dir / str(tier)
            move_image_caption_pair(image_path, caption_path, destination_dir, dry_run=dry_run)

        for tier, count in sorted(tier_counts.items()):
            logger.info("Tier %s: %s image(s)", tier, count)

    active_tiers = [tier for tier in tiers if tier_counts.get(tier, 0) > 0]

    for tier in tiers:
        tier_dir = source_dir / str(tier)
        if tier_dir_has_images(tier_dir, caption_extension) and tier not in active_tiers:
            active_tiers.append(tier)
    active_tiers.sort()

    if not active_tiers:
        logger.warning("No active tiers found; leaving %s unchanged", config_path)
        return Counter()

    config_text = render_config(
        preamble=preamble,
        general=general,
        tiers=active_tiers,
        source_dir=source_dir,
    )
    logger.info("Active tiers for config: %s", active_tiers)
    if dry_run:
        logger.info("Config preview:\n%s", config_text)
    else:
        config_path.parent.mkdir(parents=True, exist_ok=True)
        config_path.write_text(config_text, encoding="utf-8")
        logger.info("Wrote %s", config_path)

    return Counter({tier: tier_counts.get(tier, 0) for tier in active_tiers})


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
    args = parse_args()

    source_dir = args.source_dir
    config_path = args.config
    _, config = load_config(config_path)
    tiers = parse_tiers_arg(args.tiers, config)

    logger.info("Source directory: %s", source_dir)
    logger.info("Config path: %s", config_path)
    logger.info("Candidate tiers: %s", tiers)
    if args.dry_run:
        logger.info("Dry run enabled; no files will be moved or written")

    sort_dataset(
        source_dir=source_dir,
        config_path=config_path,
        tiers=tiers,
        dry_run=args.dry_run,
    )


if __name__ == "__main__":
    main()
